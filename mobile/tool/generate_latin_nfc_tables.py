#!/usr/bin/env python3
"""Generate canonical (NFC) tables for Latin letters used by OCR text.

Covers Latin-1 Supplement, Latin Extended-A/B and Latin Extended Additional,
which contains every precomposed Vietnamese letter. Output is deterministic and
derived from Python's unicodedata (the Unicode Character Database).

Usage: python3 tool/generate_latin_nfc_tables.py > lib/ocr/domain/latin_nfc_tables.g.dart
"""
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x1E00, 0x1EFF)]

decomp = {}
for lo, hi in RANGES:
    for cp in range(lo, hi + 1):
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith('<'):
            continue  # compatibility decompositions are not canonical
        decomp[cp] = [int(x, 16) for x in d.split()]

# Singleton canonical marks that ML Kit or keyboards may emit.
for cp in (0x0340, 0x0341, 0x0343):
    d = unicodedata.decomposition(chr(cp))
    decomp[cp] = [int(x, 16) for x in d.split()]

marks = set()
for parts in decomp.values():
    for p in parts[1:]:
        marks.add(p)
for cp in range(0x0300, 0x0370):
    if unicodedata.combining(chr(cp)):
        marks.add(cp)
ccc = {m: unicodedata.combining(chr(m)) for m in sorted(marks) if unicodedata.combining(chr(m))}

# Pairwise primary composites; composition exclusions are absent in these ranges,
# but re-check through NFC to be safe.
compose = {}
for cp, parts in decomp.items():
    if len(parts) == 2 and unicodedata.normalize('NFC', chr(parts[0]) + chr(parts[1])) == chr(cp):
        compose[(parts[0], parts[1])] = cp

print('// GENERATED by tool/generate_latin_nfc_tables.py — do not edit.')
print(f'// Unicode {unicodedata.unidata_version}. Latin-1, Latin Extended-A/B, Latin Extended Additional.')
print()
print('const latinCanonicalDecomposition = <int, List<int>>{')
for cp in sorted(decomp):
    print(f'  0x{cp:04X}: [{", ".join(f"0x{p:04X}" for p in decomp[cp])}],')
print('};')
print()
print('const latinCombiningClass = <int, int>{')
for cp in sorted(ccc):
    print(f'  0x{cp:04X}: {ccc[cp]},')
print('};')
print()
print('/// Key: (starter << 21) | mark.')
print('const latinPrimaryComposite = <int, int>{')
for (a, b) in sorted(compose):
    print(f'  0x{(a << 21) | b:X}: 0x{compose[(a, b)]:04X},')
print('};')
